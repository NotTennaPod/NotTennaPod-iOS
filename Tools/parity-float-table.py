#!/usr/bin/env python3 -I
# Writes Sources/NotTennaPodCore/Sync/Parity/ParityFloatTables.swift: the 128-bit powers of ten of Go 1.27.1's
# strconv (src/internal/strconv/pow10tab.go), computed as its pow10gen.go computes them. With a Go toolchain's
# pow10tab.go as the argument, it checks the table against it first:
#   python3 -I Tools/parity-float-table.py [path/to/go/src/internal/strconv/pow10tab.go]
import os
import re
import sys
from fractions import Fraction

MIN_EXP, MAX_EXP = -348, 347
MASK = (1 << 64) - 1

rows = []
for e in range(MIN_EXP, MAX_EXP + 1):
    r = Fraction(10) ** e
    be = 0
    while r < 1 << 128:
        r *= 2
        be += 1
    while r >= 1 << 128:
        r /= 2
        be -= 1
    d = r.numerator // r.denominator
    hi, lo = divmod(d, 1 << 64)
    if r.denominator != 1:
        lo = (lo + 1) & MASK
        if lo == 0:
            hi += 1
    if lo != 0:
        hi += 1
        lo = (-lo) & MASK
    rows.append((hi, lo, e, be))

if len(sys.argv) > 1:
    go = re.findall(r'\{(0x[0-9a-f]+), (0x[0-9a-f]+)\}, // 1e(-?\d+) \* 2\*\*(-?\d+)', open(sys.argv[1]).read())
    want = [(int(h, 16), int(l, 16), int(e), int(b)) for h, l, e, b in go]
    if want != rows:
        sys.exit("parity-float-table: the computed table differs from " + sys.argv[1])
    print("parity-float-table: equal to " + sys.argv[1])

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, "Sources/NotTennaPodCore/Sync/Parity/ParityFloatTables.swift")
with open(out, "w") as f:
    f.write("// Generated by Tools/parity-float-table.py. Do not edit.\n")
    f.write("// Go 1.27.1 strconv's pow10Tab (src/internal/strconv/pow10tab.go): 10^p for p in %d...%d as 128-bit\n" % (MIN_EXP, MAX_EXP))
    f.write("// mantissas hi << 64 - lo, scaled so that the high bit is set.\n\n")
    f.write("enum ParityFloatTables {\n")
    f.write("    static let pow10Min = %d\n" % MIN_EXP)
    f.write("    static let pow10Max = %d\n\n" % MAX_EXP)
    for name, index in (("pow10Hi", 0), ("pow10Lo", 1)):
        f.write("    static let %s: [UInt64] = [\n" % name)
        for i in range(0, len(rows), 4):
            f.write("        " + ", ".join("0x%016x" % row[index] for row in rows[i:i + 4]) + ",\n")
        f.write("    ]\n\n")
    f.write("}\n")
print("parity-float-table: wrote " + out)
